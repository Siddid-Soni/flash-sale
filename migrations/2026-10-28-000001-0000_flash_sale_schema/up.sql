-- Users are guests only (POST /v1/session): `username` and `email` stay NULL
-- and exist for a future registration flow.
CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(255) UNIQUE,
    email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A product is a sale: its id is the sale id used in every Redis key.
-- `sold` only rises in the confirming transaction (conditional UPDATE);
-- stock being reserved lives in Redis.
CREATE TABLE products (
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
    total_inventory INTEGER NOT NULL,
    sold INTEGER NOT NULL DEFAULT 0,
    sale_start_time TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (sold BETWEEN 0 AND total_inventory)
);

CREATE TYPE order_status AS ENUM (
    'PENDING', 'AWAITING_PAYMENT', 'CONFIRMED', 'EXPIRED', 'FAILED', 'REFUNDED'
);

-- Created by an order processor when it consumes a checkout event.
-- `queue_ticket_id` is `<sale>.<uuid>`, generated by the Order Service.
CREATE TABLE orders (
    id BIGSERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    product_id INTEGER NOT NULL REFERENCES products(id),
    queue_ticket_id TEXT NOT NULL UNIQUE,
    idempotency_key TEXT NOT NULL,
    status order_status NOT NULL DEFAULT 'PENDING',
    amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
    payment_session_id TEXT UNIQUE,
    -- Set together with `expires_at` when the order becomes AWAITING_PAYMENT
    checkout_url TEXT,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, idempotency_key)
);

SELECT diesel_manage_updated_at('orders');

-- One live order per user and product, whatever the Redis markers say
CREATE UNIQUE INDEX orders_one_live_per_user_product_idx ON orders (user_id, product_id)
    WHERE status IN ('PENDING', 'AWAITING_PAYMENT', 'CONFIRMED');

CREATE INDEX orders_status_expires_at_idx ON orders (status, expires_at);

CREATE TABLE payment_inbox (
    id BIGSERIAL PRIMARY KEY,
    provider_event_id VARCHAR(255) UNIQUE NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    payload JSONB NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT
);

-- The order processors only scan unprocessed rows
CREATE INDEX payment_inbox_unprocessed_idx ON payment_inbox (received_at)
    WHERE processed_at IS NULL;
